if ($pdoDom) {
    try {
        $dbDomPackages = $pdoDom->query("SELECT * FROM `packages` WHERE `category` = 'domestic' AND `status` = 'active' ORDER BY `id` DESC")->fetchAll();
        if (!empty($dbDomPackages)) {
            $dynamicDomPackages = [];
            foreach ($dbDomPackages as $dbh) {
                // Inclusions resolution
                $inclusions = [];
                if (!empty($dbh['inclusions'])) {
                    $decInc = json_decode($dbh['inclusions'], true);
                    if (is_array($decInc)) {
                        foreach ($decInc as $item) {
                            $itemStr = is_string($item) ? $item : ($item['label'] ?? '');
                            $icon = 'fa-solid fa-circle-check';
                            $lower = strtolower($itemStr);
                            if (str_contains($lower, 'hotel') || str_contains($lower, 'resort') || str_contains($lower, 'stay')) {
                                $icon = 'fa-solid fa-hotel';
                            } elseif (str_contains($lower, 'breakfast') || str_contains($lower, 'meal') || str_contains($lower, 'dinner') || str_contains($lower, 'food')) {
                                $icon = 'fa-solid fa-utensils';
                            } elseif (str_contains($lower, 'cab') || str_contains($lower, 'car') || str_contains($lower, 'transfer') || str_contains($lower, 'ac')) {
                                $icon = 'fa-solid fa-car';
                            } elseif (str_contains($lower, 'houseboat') || str_contains($lower, 'shikara') || str_contains($lower, 'boat') || str_contains($lower, 'cruise')) {
                                $icon = 'fa-solid fa-sailboat';
                            } elseif (str_contains($lower, 'spa') || str_contains($lower, 'massage')) {
                                $icon = 'fa-solid fa-spa';
                            } elseif (str_contains($lower, 'sightseeing') || str_contains($lower, 'tour') || str_contains($lower, 'guide')) {
                                $icon = 'fa-solid fa-camera';
                            }
                            $shortLabel = mb_strimwidth($itemStr, 0, 14, '..');
                            $inclusions[] = ['icon' => $icon, 'label' => $shortLabel];
                            if (count($inclusions) >= 6) break;
                        }
                    }
                }
                if (empty($inclusions)) {
                    $inclusions = [
                        ['icon' => 'fa-solid fa-hotel', 'label' => '4★ Hotel'],
                        ['icon' => 'fa-solid fa-utensils', 'label' => 'Breakfast'],
                        ['icon' => 'fa-solid fa-car', 'label' => 'Private AC'],
                        ['icon' => 'fa-solid fa-camera', 'label' => 'Sightseeing'],
                        ['icon' => 'fa-solid fa-shield-halved', 'label' => 'Tour Guide'],
                        ['icon' => 'fa-solid fa-spa', 'label' => 'Spa Deal']
                    ];
                }

                // Filter categories logic
                $rawCircuit = strtolower($dbh['circuit_type'] . ' ' . $dbh['location'] . ' ' . $dbh['badge']);
                $categories = ['all'];
                if (str_contains($rawCircuit, 'honeymoon') || str_contains($rawCircuit, 'romantic')) $categories[] = 'honeymoon';
                if (str_contains($rawCircuit, 'hill') || str_contains($rawCircuit, 'mountain') || str_contains($rawCircuit, 'kashmir') || str_contains($rawCircuit, 'manali') || str_contains($rawCircuit, 'shimla') || str_contains($rawCircuit, 'nainital')) $categories[] = 'hills';
                if (str_contains($rawCircuit, 'beach') || str_contains($rawCircuit, 'goa') || str_contains($rawCircuit, 'andaman') || str_contains($rawCircuit, 'kerala')) $categories[] = 'beaches';
                if (str_contains($rawCircuit, 'adventure') || str_contains($rawCircuit, 'trek') || str_contains($rawCircuit, 'rafting') || str_contains($rawCircuit, 'ladakh')) $categories[] = 'adventure';
                $catString = implode(' ', array_unique($categories));

                $img = !empty($dbh['featured_image']) ? $dbh['featured_image'] : 'https://images.unsplash.com/photo-1595815771614-ade9d652a65d?auto=format&fit=crop&w=800&q=80';

                $dynamicDomPackages[] = [
                    'id' => $dbh['id'],
                    'slug' => $dbh['slug'] ?? '',
                    'title' => $dbh['title'],
                    'route' => $dbh['location'] ?: 'Incredible India Circuit',
                    'duration' => $dbh['duration_text'] ?: ($dbh['duration_nights'] . 'N / ' . $dbh['duration_days'] . 'D'),
                    'badge' => $dbh['badge'] ?: 'Bestseller',
                    'badge_class' => 'bg-brand-600 text-white',
                    'category' => $catString,
                    'image' => $img,
                    'alt' => $dbh['title'],
                    'description' => $dbh['subtitle'] ?: 'Handcrafted holiday package with verified 4-star stays, private sanitized cabs, authentic meals, and 24x7 local support.',
                    'inclusions' => $inclusions
                ];
            }
            // Use 100% dynamic domestic packages from database
            $domesticPackages = $dynamicDomPackages;
        }
    } catch (Exception $e) {
        // Fallback silently
    }
}
